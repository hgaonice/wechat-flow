#!/usr/bin/env bash
# Install/refresh the wechat-flow systemd timers.
# Run on the target host (192.168.0.250) as root.
set -euo pipefail

APP_DIR="${APP_DIR:-/root/wechat-flow}"
UNIT_DIR="${UNIT_DIR:-/etc/systemd/system}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "==> Installing units from $HERE to $UNIT_DIR"
# plan/publish 的 unit 就放在 deploy/ 下；C1 的 keepalive 两个 unit 在 deploy/systemd/ 下。
install -m 0644 "$HERE"/wechat-plan.service "$HERE"/wechat-plan.timer \
                "$HERE"/wechat-publish.service "$HERE"/wechat-publish.timer "$UNIT_DIR"/
for u in wechat-keepalive.service wechat-keepalive.timer; do
  install -m 0644 "$HERE/systemd/$u" "$UNIT_DIR/$u"
done

# C1 Step5（浏览器生命周期解耦）：xvfb + 浏览器模板 unit。
# 逻辑放在 deploy/systemd/install-browser-units.sh（install-console.sh 也调它，
# 250 走的是控制台安装器）。它只 enable Xvfb、不 enable 任何 alias 实例。
bash "$HERE/systemd/install-browser-units.sh"

# unit 里 ExecStart 的 bun 路径是硬编码的；路径漂了 unit 会直接起不来，这里提前喊一声。
BUN_PATH="${WFC_BUN_PATH:-/root/.nvm/versions/node/v24.14.1/bin/bun}"
if [ ! -x "$BUN_PATH" ]; then
  echo "⚠️  $BUN_PATH 不存在 —— wechat-keepalive 的 ExecStart 会失败（改 unit 里的路径或修 bun）" >&2
fi

# C1: keepalive interval is tunable without editing the unit file.
#   WFC_KEEPALIVE_HOURS=5 bash deploy/install.sh     # default in the unit file
#   WFC_KEEPALIVE_HOURS=4 bash deploy/install.sh     # 4-hour cycle
# Unset → any previously rendered drop-in is removed (unit file wins again).
KEEPALIVE_DROPIN_DIR="$UNIT_DIR/wechat-keepalive.timer.d"
if [ -n "${WFC_KEEPALIVE_HOURS:-}" ]; then
  case "$WFC_KEEPALIVE_HOURS" in
    ''|*[!0-9]*|0)
      echo "✖ WFC_KEEPALIVE_HOURS 必须是正整数（收到：$WFC_KEEPALIVE_HOURS）" >&2
      exit 2
      ;;
  esac
  echo "==> Rendering keepalive interval drop-in: ${WFC_KEEPALIVE_HOURS}h"
  install -d -m 0755 "$KEEPALIVE_DROPIN_DIR"
  cat > "$KEEPALIVE_DROPIN_DIR/interval.conf" <<EOF
# Generated by deploy/install.sh from WFC_KEEPALIVE_HOURS=${WFC_KEEPALIVE_HOURS}
# Delete this file (or re-run install.sh without the env var) to fall back
# to the interval baked into wechat-keepalive.timer.
[Timer]
OnUnitActiveSec=${WFC_KEEPALIVE_HOURS}h
EOF
  chmod 0644 "$KEEPALIVE_DROPIN_DIR/interval.conf"
elif [ -d "$KEEPALIVE_DROPIN_DIR" ]; then
  echo "==> Removing keepalive interval drop-in (back to unit-file default)"
  rm -f "$KEEPALIVE_DROPIN_DIR/interval.conf"
  rmdir "$KEEPALIVE_DROPIN_DIR" 2>/dev/null || true
fi

if [ ! -f "$APP_DIR/config.json" ]; then
  echo "==> Creating $APP_DIR/config.json from example"
  install -m 0600 "$APP_DIR/config.example.json" "$APP_DIR/config.json"
fi

echo "==> Patching baoyu-post-to-wechat (browser publish writes an EMPTY body without it)"
"$HERE/patch-baoyu-skill.sh" "${SKILL_DIR:-/root/.agents/skills/baoyu-post-to-wechat}"

echo "==> systemd daemon-reload"
systemctl daemon-reload

echo "==> Enabling timers"
# ⚠️ 2026-10-20 真实事故：这两个 timer 是**遗留**的 pi-agent 调度（plan 会重新生成整周计划、
# publish 会立刻跑一次生成/发布）。控制台上线后调度由 console scheduler 接管（DB 里的 plans/jobs），
# 这两个 timer 应当保持 disabled；否则跑一次 install.sh 就会立刻触发一次 plan+publish
# （publish 是幂等的会 skip，但 plan 可能覆盖 data/<alias>/plans/<period>.json）。
# 因此改为显式 opt-in。
if [ "${WFC_ENABLE_LEGACY_TIMERS:-0}" = "1" ]; then
  echo "   · 显式启用 legacy plan/publish timers（WFC_ENABLE_LEGACY_TIMERS=1）"
  systemctl enable --now wechat-plan.timer wechat-publish.timer
else
  echo "   · legacy plan/publish timers 保持原状（console scheduler 负责发布；需要时设 WFC_ENABLE_LEGACY_TIMERS=1）"
fi
# keepalive.timer is the C1 session-keeper: without it the MP ticket lapses
# after 96h and every publish starts failing on login.
systemctl enable --now wechat-keepalive.timer

echo "==> Status"
systemctl list-timers 'wechat-*' --no-pager || true
echo
echo "Manual run:  systemctl start wechat-plan.service"
echo "Logs:        journalctl -u wechat-publish.service -n 100 --no-pager"